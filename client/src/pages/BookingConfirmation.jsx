
import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";

import "./BookingConfirmation.css";

function BookingConfirmation() {
  const { id } = useParams();

  const [booking, setBooking] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    async function fetchBooking() {
      const token = localStorage.getItem("token");

      if (!token) {
        setError("Please log in to view this booking.");
        setLoading(false);
        return;
      }

      try {
        const response = await fetch(
          `http://localhost:5000/api/bookings/${id}`,
          {
            headers: {
              Authorization: `Bearer ${token}`,
            },
          }
        );

        const data = await response.json();

        if (!response.ok) {
          throw new Error(
            data.message || "Unable to load booking."
          );
        }

        setBooking(data);
      } catch (err) {
        console.error("Booking confirmation error:", err);
        setError(err.message || "Unable to load your booking.");
      } finally {
        setLoading(false);
      }
    }

    fetchBooking();
  }, [id]);

  async function handleCopyReference() {
    try {
      await navigator.clipboard.writeText(booking._id);
      setCopied(true);

      setTimeout(() => {
        setCopied(false);
      }, 2000);
    } catch (copyError) {
      console.error("Copy reference error:", copyError);
      setError(
        "Unable to copy the reference. Please select and copy it manually."
      );
    }
  }

  function formatPrice(value) {
    const amount = Number(value);

    if (!Number.isFinite(amount)) {
      return "Not available";
    }

    return `₹${amount.toLocaleString("en-IN")}`;
  }

  function formatDate(value) {
    const date = new Date(value);

    if (Number.isNaN(date.getTime())) {
      return "Not available";
    }

    return date.toLocaleDateString("en-IN", {
      day: "numeric",
      month: "short",
      year: "numeric",
    });
  }

  if (loading) {
    return (
      <main className="confirmation-page">
        <p>Loading your booking confirmation...</p>
      </main>
    );
  }

  if (error && !booking) {
    return (
      <main className="confirmation-page">
        <div className="confirmation-card">
          <h1>Booking not available</h1>
          <p>{error}</p>

          <Link
            to="/my-bookings"
            className="confirmation-button"
          >
            My Bookings
          </Link>

          <Link
            to="/"
            className="confirmation-secondary-button"
          >
            Explore Destinations
          </Link>
        </div>
      </main>
    );
  }

  if (!booking) {
    return null;
  }

  const isConfirmed = booking.status === "confirmed";

  return (
    <main className="confirmation-page">
      <section className="confirmation-card">
        <div
          className={`confirmation-success-icon ${
            isConfirmed ? "" : "confirmation-cancelled-icon"
          }`}
          aria-hidden="true"
        >
          {isConfirmed ? "✓" : "!"}
        </div>

        <p className="confirmation-eyebrow">
          DEMO BOOKING CONFIRMATION
        </p>

        <h1>
          {isConfirmed
            ? "Your demo booking is confirmed!"
            : "Booking details"}
        </h1>

        <p className="confirmation-message">
          {isConfirmed
            ? "Your booking record has been saved successfully in Travel Explorer."
            : "This booking is no longer confirmed."}
        </p>

        <div
          className={`confirmation-status ${
            isConfirmed
              ? "confirmation-status-confirmed"
              : "confirmation-status-cancelled"
          }`}
        >
          Status:{" "}
          <strong>
            {booking.status || "Unknown"}
          </strong>
        </div>

        <div className="confirmation-demo-notice">
          <strong>Important: This is a demo booking.</strong>
          <p>
            This confirmation is generated by the Travel Explorer
            application using sample hotel data and estimated prices.
            No real hotel reservation or payment has been made.
          </p>
        </div>

        <div className="confirmation-details">
          <div className="confirmation-row">
            <span>Hotel</span>
            <strong>{booking.hotelName}</strong>
          </div>

          <div className="confirmation-row">
            <span>Guest name</span>
            <strong>{booking.guestName}</strong>
          </div>

          <div className="confirmation-row">
            <span>Email</span>
            <strong>{booking.guestEmail}</strong>
          </div>

          <div className="confirmation-row">
            <span>Check-in</span>
            <strong>{formatDate(booking.checkIn)}</strong>
          </div>

          <div className="confirmation-row">
            <span>Check-out</span>
            <strong>{formatDate(booking.checkOut)}</strong>
          </div>

          <div className="confirmation-row">
            <span>Guests</span>
            <strong>{booking.guests}</strong>
          </div>

          <div className="confirmation-row">
            <span>Estimated price per night</span>
            <strong>
              {formatPrice(booking.pricePerNight)}
            </strong>
          </div>

          <div className="confirmation-total">
            <span>Estimated total</span>
            <strong>
              {formatPrice(booking.totalPrice)}
            </strong>
          </div>

          <div className="confirmation-reference">
            <span>Demo booking reference</span>

            <strong className="confirmation-reference-id">
              {booking._id}
            </strong>

            <button
              type="button"
              className="confirmation-copy-button"
              onClick={handleCopyReference}
            >
              {copied ? "Copied!" : "Copy Reference"}
            </button>
          </div>
        </div>

        {error && (
          <p className="confirmation-inline-error" role="alert">
            {error}
          </p>
        )}

        <div className="confirmation-actions">
          <Link
            to="/my-bookings"
            className="confirmation-button"
          >
            My Bookings
          </Link>

          <Link
            to="/"
            className="confirmation-secondary-button"
          >
            Explore Destinations
          </Link>
        </div>
      </section>
    </main>
  );
}

export default BookingConfirmation;
