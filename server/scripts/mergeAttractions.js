const fs = require('fs');
const path = require('path');
const dataDir = path.resolve(__dirname, '..', 'data');
const sourcePath = path.join(dataDir, 'attractions.js');
const additionsPath = path.join(dataDir, 'additionalAttractions.js');
if (!fs.existsSync(sourcePath) || !fs.existsSync(additionsPath)) {
  console.error('Missing data/attractions.js or data/additionalAttractions.js'); process.exit(1);
}
const existing = require(sourcePath);
const incoming = require(additionsPath);
if (!Array.isArray(existing) || !Array.isArray(incoming)) throw Error('Expected arrays in both data files');
const normalized = x => String(x || '').trim().toLocaleLowerCase('en');
const key = x => normalized(x.destination) + '::' + normalized(x.name);
const ids = new Set(existing.map(x => normalized(x.id)));
const names = new Set(existing.map(key));
const accepted = []; let skipped = 0;
for (const item of incoming) {
  if (!item.id || !item.name || !item.destination) throw Error('Invalid attraction: ' + JSON.stringify(item));
  if (ids.has(normalized(item.id)) || names.has(key(item))) { skipped++; continue; }
  ids.add(normalized(item.id)); names.add(key(item)); accepted.push(item);
}
const stamp = new Date().toISOString().replace(/[:.]/g, '-');
const backup = sourcePath + '.backup-' + stamp;
fs.copyFileSync(sourcePath, backup);
const combined = existing.concat(accepted);
const content = '// Generated by mergeAttractions.js. Backup: ' + path.basename(backup) + '\n' +
  'const attractions = ' + JSON.stringify(combined, null, 2) + ';\n\nmodule.exports = attractions;\n';
const temp = sourcePath + '.tmp';
try { fs.writeFileSync(temp, content, 'utf8'); fs.renameSync(temp, sourcePath); }
catch (error) { if (fs.existsSync(temp)) fs.unlinkSync(temp); throw error; }
console.log('Existing preserved:', existing.length);
console.log('New attractions added:', accepted.length);
console.log('Duplicates skipped:', skipped);
console.log('Total attractions:', combined.length);
console.log('Backup:', backup);
